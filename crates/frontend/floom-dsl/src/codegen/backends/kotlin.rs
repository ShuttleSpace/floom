//! Kotlin glue generator (Phase 18.2, Step 3).
//!
//! Emits one Kotlin class per component. Properties are Kotlin properties whose
//! accessors delegate to `external` (JNI) functions; events are stored Kotlin
//! lambdas. No Kotlin compiler is assumed to be present, so this backend is
//! covered by output assertions rather than a compile fixture.

use super::banner;
use crate::codegen::schema::{Access, ComponentSchema, Param, TypeRef};
use std::fmt::Write as _;

/// Kotlin spelling of a type.
fn kt_type(ty: &TypeRef) -> String {
    use TypeRef::*;
    match ty {
        Bool => "Boolean".into(),
        I8 => "Byte".into(),
        I16 => "Short".into(),
        I32 => "Int".into(),
        I64 => "Long".into(),
        U8 => "UByte".into(),
        U16 => "UShort".into(),
        U32 => "UInt".into(),
        U64 => "ULong".into(),
        F32 => "Float".into(),
        F64 => "Double".into(),
        String => "String".into(),
        Bytes => "ByteArray".into(),
        Resource(_) => "Long".into(),
        Handle(_) => "Long".into(),
        Option(t) => format!("{}?", kt_type(t)),
        Vec(t) => format!("List<{}>", kt_type(t)),
        Custom(_) => "Long".into(),
    }
}

/// `snake_case` → `camelCase`.
fn camel_case(s: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for ch in s.chars() {
        if ch == '_' {
            upper = true;
        } else if upper {
            out.push(ch.to_ascii_uppercase());
            upper = false;
        } else {
            out.push(ch);
        }
    }
    out
}

fn capitalize(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
        None => String::new(),
    }
}

fn params(params: &[Param]) -> String {
    params
        .iter()
        .map(|p| format!("{}: {}", camel_case(&p.name.0), kt_type(&p.ty)))
        .collect::<Vec<_>>()
        .join(", ")
}

fn args(params: &[Param]) -> String {
    params
        .iter()
        .map(|p| camel_case(&p.name.0))
        .collect::<Vec<_>>()
        .join(", ")
}

fn access_str(a: Access) -> &'static str {
    match a {
        Access::Read => "read",
        Access::Write => "write",
        Access::ReadWrite => "read/write",
    }
}

/// Emit the Kotlin class for `schema`.
pub fn generate(schema: &ComponentSchema) -> Vec<super::GeneratedFile> {
    let name = &schema.name.0;
    let mut out = String::new();
    let _ = writeln!(out, "// Generated by floom-codegen. DO NOT EDIT.");
    let _ = writeln!(out, "// {}", banner(schema));
    let _ = writeln!(out, "package floom.generated");
    let _ = writeln!(out);
    let _ = writeln!(out, "class {name}(private val handle: Long) {{");
    let _ = writeln!(out, "    companion object {{");
    let _ = writeln!(
        out,
        "        const val ABI_MAJOR: Int = {}",
        schema.abi.major
    );
    let _ = writeln!(
        out,
        "        const val ABI_MINOR: Int = {}",
        schema.abi.minor
    );
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(out, "    external fun destroy()");

    for p in &schema.properties {
        let n = camel_case(&p.name.0);
        let cap = capitalize(&n);
        let t = kt_type(&p.ty);
        let _ = writeln!(out);
        let _ = writeln!(
            out,
            "    // property `{}` ({})",
            p.name.0,
            access_str(p.access)
        );
        match p.access {
            Access::Read => {
                let _ = writeln!(out, "    external fun get{cap}(): {t}");
                let _ = writeln!(out, "    val {n}: {t} get() = get{cap}()");
            }
            Access::Write => {
                let _ = writeln!(out, "    external fun set{cap}(value: {t})");
                let _ = writeln!(out, "    var {n}: {t} set(value) = set{cap}(value)");
            }
            Access::ReadWrite => {
                let _ = writeln!(out, "    external fun get{cap}(): {t}");
                let _ = writeln!(out, "    external fun set{cap}(value: {t})");
                let _ = writeln!(
                    out,
                    "    var {n}: {t}\n        get() = get{cap}()\n        set(value) = set{cap}(value)"
                );
            }
        }
    }

    for c in &schema.commands {
        let n = camel_case(&c.name.0);
        let _ = writeln!(out);
        let _ = writeln!(out, "    // command `{}`", c.name.0);
        let ret = c
            .ret
            .as_ref()
            .map(|r| format!(": {}", kt_type(r)))
            .unwrap_or_default();
        let _ = writeln!(out, "    external fun {n}({}){ret}", params(&c.params));
    }

    for e in &schema.events {
        let n = camel_case(&e.name.0);
        let cap = capitalize(&n);
        let cb_args = e
            .params
            .iter()
            .map(|p| kt_type(&p.ty))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out);
        let _ = writeln!(out, "    // event `{}`", e.name.0);
        let _ = writeln!(out, "    var on{cap}: (({cb_args}) -> Unit)? = null");
    }

    let _ = writeln!(out, "}}");

    vec![super::GeneratedFile::new(format!("{name}.kt"), out)]
}

/// Kotlin argument list helper kept close to the generator for reuse.
#[allow(unused)]
fn call_args(params: &[Param]) -> String {
    args(params)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::codegen::fixtures;

    #[test]
    fn class_declares_external_accessors() {
        let s = fixtures::demo_video_player();
        let files = generate(&s);
        assert_eq!(files.len(), 1);
        assert_eq!(files[0].path, "VideoPlayer.kt");
        let k = &files[0].contents;
        assert!(k.contains("class VideoPlayer(private val handle: Long) {"));
        assert!(k.contains("const val ABI_MAJOR: Int = 1"));
        assert!(k.contains("external fun getSrc(): String"));
        assert!(k.contains("external fun setSrc(value: String)"));
        assert!(k.contains("external fun seek(ms: ULong)"));
        assert!(k.contains("external fun position(): ULong"));
        assert!(k.contains("var onEnded: (() -> Unit)? = null"));
        assert!(k.contains("var onError: ((String) -> Unit)? = null"));
    }

    #[test]
    fn wide_schema_type_mapping() {
        let s = fixtures::wide_type_coverage();
        let k = &generate(&s)[0].contents;
        assert!(k.contains("external fun getPayload(): ByteArray"));
        assert!(k.contains("external fun getTexture(): Long"));
        assert!(k.contains("external fun getMaybeCount(): Int?"));
        assert!(k.contains("external fun getSamples(): List<Float>"));
        assert!(k.contains("external fun setDevice(value: Long)"));
        assert!(k.contains("external fun submit(samples: List<Float>): ByteArray"));
    }

    #[test]
    fn camel_case_conversion() {
        assert_eq!(camel_case("maybe_count"), "maybeCount");
        assert_eq!(camel_case("src"), "src");
        assert_eq!(
            crate::codegen::backends::snake_case("VideoPlayer"),
            "video_player"
        );
    }
}
