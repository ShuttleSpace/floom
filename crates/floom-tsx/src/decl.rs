//! Generate `.d.ts` editor declarations from a `UiDocument`'s vocabulary.
//!
//! The declarations mirror what `floom-dsl` accepts: one interface per widget
//! kind, with its declared style/layout/widget props as optional fields and its
//! emitted events as `onXxx` handler fields. This is the same information the
//! schema tables carry, surfaced for editors — nsh emits an analogous
//! `.nsh/types` for its components.

use floom_ui_ir::{
    EventName, NodeKind, UiDocument, ValueType, all_prop_names, events_for, prop_spec,
};

/// Generate a `.d.ts` string describing every widget kind used by `doc`.
pub fn generate(doc: &UiDocument) -> String {
    let mut out = String::from("// @generated by floom-tsx. Do not edit.\n\n");

    // `createSignal` and friends from the reactive shim.
    out.push_str(
        "export declare function createSignal<T>(value: T): [ReadonlySignal<T>, (v: T) => void];\n",
    );
    out.push_str("export declare function createMemo<T>(fn: () => T): ReadonlySignal<T>;\n");
    out.push_str("export declare function createEffect(fn: () => void): void;\n");
    out.push_str("export declare function provideContext<T>(name: string, value: T): void;\n");
    out.push_str("export declare function useContext<T>(name: string): T;\n\n");

    // `doc.kinds()` returns the node kinds in use, sorted and de-duplicated.
    for kind in doc.kinds() {
        out.push_str(&interface_for(kind));
        out.push('\n');
    }

    // The entry surface: `mount`, and the `window` / `app` / `platform` handles
    // a TSX module drives the runtime through. These mirror what `entry::resolve`
    // accepts, so the editor flags unknown methods.
    out.push_str(ENTRY_DECL);
    out
}

/// `declare module "floom"` — the TSX side of the unified runtime entry.
///
/// `mount(App)` replaces the older "export a default view" shape with an
/// nsh-like one: the module names its root component and tweaks the window and
/// platform through small callable handles, all at module scope.
const ENTRY_DECL: &str = r#"
export type JSXElementConstructor = () => JSX.Element;

export declare function mount(component: JSXElementConstructor): void;

export declare const app: {
  /** Default window title; `window.setTitle` overrides it. */
  setName(name: string): void;
};

export declare const window: {
  setTitle(title: string): void;
  setSize(width: number, height: number): void;
  setSize(size: string): void;
  setResizable(resizable: boolean): void;
};

export declare const platform: {
  /**
   * Require a capability from the compiled-in backend.
   * @param capability one of windowing, clipboard, ime, accessibility, webgpu, software_render, touch, native_view
   * @param onUnsupported warn | fail | exit
   */
  require(capability: string, onUnsupported: string): void;
};
"#;

/// One `interface` per kind, listing its props and event handlers.
fn interface_for(kind: NodeKind) -> String {
    let mut lines = vec![format!("export interface {}Props {{", kind_name(kind))];

    for name in all_prop_names() {
        if let Some(spec) = prop_spec(kind, name) {
            let ts_ty = ts_type(spec.ty);
            let optional = if matches!(spec.ty, ValueType::Bool) {
                "" // `checked` on a checkbox reads naturally as optional anyway
            } else {
                "?"
            };
            lines.push(format!("  {name}{optional}: {ts_ty};"));
        }
    }

    for event in events_for(kind) {
        lines.push(format!("  {}?: () => void;", event_handler_name(event)));
    }

    lines.push("}".to_string());
    lines.join("\n")
}

/// The TSX component name for a kind: `TextField` (not the IR's `text_field`).
fn kind_name(kind: NodeKind) -> String {
    // `prop_spec`/`name` spellings are snake_case; TSX uses PascalCase.
    match kind {
        NodeKind::Native(n) => format!("Native{}", format!("{n:?}")),
        other => other
            .name()
            .split('_')
            .map(|s| {
                let mut c = s.chars();
                match c.next() {
                    Some(first) => first.to_uppercase().collect::<String>() + c.as_str(),
                    None => String::new(),
                }
            })
            .collect::<String>(),
    }
}

/// Map an IR value type to its TypeScript surface type.
fn ts_type(ty: ValueType) -> &'static str {
    match ty {
        ValueType::Bool => "boolean",
        ValueType::Int | ValueType::Number => "number",
        ValueType::Text => "string",
        ValueType::Color => "string",
        ValueType::Ident => "string",
        ValueType::List => "unknown[]",
    }
}

/// `Click` becomes `onClick` (camelCase, as TSX authors write it).
fn event_handler_name(event: EventName) -> String {
    let name = event.name();
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => format!("on{}{}", first.to_uppercase(), chars.as_str()),
        None => String::from("on"),
    }
}
