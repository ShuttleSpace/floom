//! TSX as a whole application: the entry file declares the window too.
//!
//! A `floom run app.tsx` app is one TSX file whose root is an `<App>` wrapper:
//!
//! ```tsx
//! <App title="Counter" size="480x320">
//!   <Stack axis="vertical">
//!     <Text label={count()} />
//!   </Stack>
//! </App>
//! ```
//!
//! The compiler lowers the wrapper's child into the widget tree and reads the
//! wrapper's attributes for the window. Emitting then produces two files: the
//! widget program (`ui_gen.rs`) and a `main.rs` that mounts it through
//! [`floom::run`], so the author never writes Rust.

use std::path::Path;

use floom_ui_ir::{PropValue, UiDocument};

use crate::entry::AppConfig;
use crate::error::{Result, TsxError};
use crate::lower;
use crate::parser::parse;

/// A compiled TSX application: its widget tree plus its window declaration.
#[derive(Debug, Clone)]
pub struct CompiledApp {
    pub document: UiDocument,
    pub config: AppConfig,
}

/// The two generated Rust files of a TSX app.
#[derive(Debug, Clone)]
pub struct Generated {
    /// The widget program, included by `main.rs` as `mod ui_gen`.
    pub ui_gen: String,
    /// The binary entry that mounts `ui_gen::build()` via `floom::run`.
    pub main: String,
}

/// Compile a TSX application source string.
pub fn compile(source: &str) -> Result<CompiledApp> {
    let parsed = parse(source)?;
    let (document, config) = lower::lower_with_app(&parsed)?;
    Ok(CompiledApp { document, config })
}

/// Read and compile a TSX application file.
pub fn compile_file(path: &Path) -> Result<CompiledApp> {
    let source = std::fs::read_to_string(path)
        .map_err(|e| TsxError::new(format!("cannot read {}: {e}", path.display())))?;
    compile(&source)
}

/// Emit the widget program for an app.
pub fn emit_ui_gen(document: &UiDocument) -> Result<String> {
    let options = floom_dsl::EmitOptions {
        widgets: floom_dsl::WidgetSource::Primitives,
        reactive: is_reactive(document),
        ..Default::default()
    };
    let mut code = floom_dsl::emit(document, &options)
        .map_err(|e| TsxError::new(format!("emit failed: {e}")))?
        .code;
    // The emitter opens the file with a crate-level inner attribute. The file is
    // `include!`d inside `mod ui_gen`, where inner attributes are illegal, so the
    // attribute moves to the `mod` declaration in the generated `main.rs`.
    if code.contains("#![allow(unused_imports, clippy::all)]\n") {
        code = code.replacen("#![allow(unused_imports, clippy::all)]\n", "", 1);
    }
    Ok(code)
}

/// Generate the `main.rs` that mounts the emitted tree through `floom::run`.
///
/// This is the door that removes Rust from a TSX app: the binary has no app
/// code of its own beyond the mount. It calls the unified platform entry, which
/// is the single API an app sees, and honours any `platform.require` the TSX
/// declared before the loop starts.
pub fn emit_main(config: &AppConfig) -> String {
    let mut requires = String::new();
    for req in &config.requires {
        requires.push_str(&format!(
            "    floom::platform::require(\n        floom::platform::Capability::{cap},\n        floom::platform::OnUnsupported::{policy},\n    )\n    .map_err(|e| e.to_string())?;\n",
            cap = capability_variant(&req.capability),
            policy = policy_variant(&req.policy),
        ));
    }

    format!(
        "// @generated by floem-tsx from a `.tsx` application; do not edit.\n\
         \n\
         use floom::prelude::*;\n\
         \n\
         #[allow(unused_imports, clippy::all)]\n\
         mod ui_gen {{\n\
         \x20   include!(\"ui_gen.rs\");\n\
         }}\n\
         \n\
         fn main() -> Result<(), String> {{\n\
         {requires}\
         \x20   floom::platform::current().run(\n\
         \x20       floom::platform::AppRequest {{\n\
         \x20           title: {title}.to_string(),\n\
         \x20           size: Size::new({width}, {height}),\n\
         \x20           resizable: {resizable},\n\
         \x20       }},\n\
         \x20       Box::new(|host: &mut WidgetHost| {{\n\
         \x20           host.mount_root_boxed(LayoutStyle::default(), ui_gen::build());\n\
         \x20       }}),\n\
         \x20   )\n\
         }}\n",
        requires = requires,
        title = rust_str_lit(&config.title),
        width = float_lit(config.width),
        height = float_lit(config.height),
        resizable = config.resizable,
    )
}

/// `ime` -> `IME`, the `Capability` variant the emitted Rust names.
fn capability_variant(cap: &str) -> &'static str {
    match cap {
        "windowing" => "WINDOWING",
        "clipboard" => "CLIPBOARD",
        "ime" => "IME",
        "accessibility" => "ACCESSIBILITY",
        "webgpu" => "WEBGPU",
        "software_render" => "SOFTWARE_RENDER",
        "touch" => "TOUCH",
        "native_view" => "NATIVE_VIEW",
        // `entry::resolve` only accepts the names above, so this is unreachable.
        _ => "WINDOWING",
    }
}

/// `warn` -> `Warn`, the `OnUnsupported` variant the emitted Rust names.
fn policy_variant(policy: &str) -> &'static str {
    match policy {
        "warn" => "Warn",
        "fail" => "Fail",
        "exit" => "Exit",
        _ => "Warn",
    }
}

/// Compile a source string all the way to the generated Rust files.
pub fn generate(source: &str) -> Result<Generated> {
    let app = compile(source)?;
    Ok(Generated {
        ui_gen: emit_ui_gen(&app.document)?,
        main: emit_main(&app.config),
    })
}

/// A document is reactive when any property reads a binding; only then does the
/// emitted program need `floom_signal` and the closure-capture form.
fn is_reactive(document: &UiDocument) -> bool {
    document.nodes.iter().any(|node| {
        node.props
            .iter()
            .any(|p| matches!(p.value, PropValue::Ref(_)))
    })
}

/// A Rust string literal for an arbitrary title (quotes/backslashes escaped).
fn rust_str_lit(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A float literal that always parses as `f64` (`480` -> `480.0`).
fn float_lit(v: f64) -> String {
    if v.fract() == 0.0 && v.is_finite() {
        format!("{v:.1}")
    } else {
        format!("{v}")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const APP: &str = r#"
        export default function App() {
            return (
                <App title="Counter" size="640x400">
                    <Stack axis="vertical">
                        <Text label="hello" />
                    </Stack>
                </App>
            );
        }
    "#;

    #[test]
    fn reads_window_config_from_app_wrapper() {
        let app = compile(APP).expect("compile");
        assert_eq!(app.config.title, "Counter");
        assert_eq!(app.config.width, 640.0);
        assert_eq!(app.config.height, 400.0);
        // The wrapper is not a widget: its child is the tree root.
        let root = app
            .document
            .nodes
            .iter()
            .find(|n| n.key == app.document.root)
            .expect("root node");
        assert_eq!(root.kind, floom_ui_ir::NodeKind::Stack);
    }

    #[test]
    fn emits_a_main_that_mounts_the_generated_tree() {
        let generated = generate(APP).expect("generate");
        assert!(generated.main.contains("mod ui_gen"));
        assert!(generated.main.contains("include!(\"ui_gen.rs\")"));
        assert!(generated.main.contains("floom::platform::current().run("));
        assert!(generated.main.contains("mount_root_boxed"));
        assert!(generated.main.contains("use floom::prelude::*;"));
        assert!(generated.main.contains("Size::new(640.0, 400.0)"));
        assert!(generated.main.contains("floom::platform::AppRequest"));
        // The crate-level attribute the emitter writes must not survive: the
        // file is included inside a module.
        assert!(!generated.ui_gen.contains("#![allow("));
    }

    #[test]
    fn app_wrapper_is_optional_and_defaults_apply() {
        let app = compile("<Stack><Text label=\"hi\" /></Stack>").expect("compile");
        assert_eq!(app.config, AppConfig::default());
    }

    #[test]
    fn title_is_escaped_into_the_generated_literal() {
        let out = emit_main(&AppConfig {
            title: "a \"quoted\" \\ title".into(),
            width: 1.0,
            height: 2.0,
            resizable: true,
            requires: Vec::new(),
        });
        assert!(out.contains(r#""a \"quoted\" \\ title""#));
    }
}
