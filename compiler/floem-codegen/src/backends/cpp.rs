//! C++17 facade generator (Phase 18.2, Step 4 — Harmony/C++ bindings).
//!
//! Emits a header-only RAII wrapper over the C ABI from [`super::c`]. The class
//! owns nothing (the native side owns the instance); it is a typed, safe view
//! over the opaque handle: `std::string` for `String`, `std::function` for
//! events, and the C spelling for everything else.

use super::c::{c_callback_params, c_type};
use super::{banner, macro_prefix, snake_case, symbol_prefix};
use crate::schema::{Access, ComponentSchema, Param, TypeRef};
use std::fmt::Write as _;

/// The C++ spelling of a value parameter.
fn param_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::String => "const std::string&".into(),
        other => c_type(other),
    }
}

/// The C++ spelling of a return value.
fn ret_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::String => "std::string".into(),
        other => c_type(other),
    }
}

/// Convert a C++ argument expression `expr` into the C argument for `ty`.
fn to_c(expr: &str, ty: &TypeRef) -> String {
    match ty {
        TypeRef::String => format!("{expr}.c_str()"),
        _ => expr.to_string(),
    }
}

/// Convert a C result expression `expr` into the C++ value for `ty`.
fn from_c(expr: &str, ty: &TypeRef) -> String {
    match ty {
        TypeRef::String => format!("({expr} ? std::string({expr}) : std::string())"),
        _ => expr.to_string(),
    }
}

fn params_call(params: &[Param]) -> String {
    params
        .iter()
        .map(|p| to_c(&snake_case(&p.name.0), &p.ty))
        .collect::<Vec<_>>()
        .join(", ")
}

fn params_decl(params: &[Param]) -> String {
    params
        .iter()
        .map(|p| format!("{} {}", param_type(&p.ty), snake_case(&p.name.0)))
        .collect::<Vec<_>>()
        .join(", ")
}

/// Event callback parameter types use the C spelling (borrowed values), so the
/// trampoline needs no conversion and cannot dangle. Struct-shaped values are
/// pointers, matching the callback typedef in the C header.
fn event_fn_type(e: &crate::schema::EventSchema) -> String {
    let args = c_callback_params(&e.params)
        .into_iter()
        .map(|(t, _)| t)
        .collect::<Vec<_>>()
        .join(", ");
    format!("std::function<void({args})>")
}

fn event_trampoline_args(params: &[Param]) -> String {
    c_callback_params(params)
        .into_iter()
        .map(|(t, n)| format!("{t} {n}"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// Emit the C++ facade header for `schema`.
pub fn generate(schema: &ComponentSchema) -> Vec<super::GeneratedFile> {
    let prefix = symbol_prefix(schema);
    let macro_p = macro_prefix(schema);
    let guard = format!("{macro_p}_GLUE_HPP");
    let class = &schema.name.0;
    let handle = format!("{prefix}_handle");

    let mut out = String::new();
    let _ = writeln!(out, "// Generated by floem-codegen. DO NOT EDIT.");
    let _ = writeln!(out, "// {}", banner(schema));
    let _ = writeln!(out, "#ifndef {guard}");
    let _ = writeln!(out, "#define {guard}");
    let _ = writeln!(out);
    let _ = writeln!(out, "#include \"{prefix}_abi.h\"");
    let _ = writeln!(out);
    let _ = writeln!(out, "#include <functional>");
    let _ = writeln!(out, "#include <string>");
    let _ = writeln!(out, "#include <utility>");
    let _ = writeln!(out);
    let _ = writeln!(out, "namespace floem_gen {{");
    let _ = writeln!(out);
    let _ = writeln!(out, "class {class} {{");
    let _ = writeln!(out, "public:");
    let _ = writeln!(out, "  using Handle = {handle};");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "  static constexpr uint32_t abi_major = {};",
        schema.abi.major
    );
    let _ = writeln!(
        out,
        "  static constexpr uint32_t abi_minor = {};",
        schema.abi.minor
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "  explicit {class}(Handle *handle) : handle_(handle) {{}}"
    );
    let _ = writeln!(out, "  Handle *handle() const {{ return handle_; }}");
    let _ = writeln!(
        out,
        "  void destroy() {{ if (handle_) {{ {prefix}_destroy(handle_); handle_ = nullptr; }} }}"
    );

    for p in &schema.properties {
        let name = snake_case(&p.name.0);
        let _ = writeln!(out);
        let _ = writeln!(
            out,
            "  // property `{}` ({})",
            p.name.0,
            access_str(p.access)
        );
        if matches!(p.access, Access::Write | Access::ReadWrite) {
            let _ = writeln!(
                out,
                "  void set_{name}({} value) {{ {prefix}_set_{name}(handle_, {}); }}",
                param_type(&p.ty),
                to_c("value", &p.ty)
            );
        }
        if matches!(p.access, Access::Read | Access::ReadWrite) {
            let _ = writeln!(
                out,
                "  {} get_{name}() const {{ return {}; }}",
                ret_type(&p.ty),
                from_c(&format!("{prefix}_get_{name}(handle_)"), &p.ty)
            );
        }
    }

    for c in &schema.commands {
        let name = snake_case(&c.name.0);
        let _ = writeln!(out);
        let _ = writeln!(out, "  // command `{}`", c.name.0);
        let call = format!(
            "{prefix}_cmd_{name}(handle_{})",
            prefix_args(&params_call(&c.params))
        );
        match &c.ret {
            Some(r) => {
                let _ = writeln!(
                    out,
                    "  {} cmd_{name}({}) const {{ return {}; }}",
                    ret_type(r),
                    params_decl(&c.params),
                    from_c(&call, r)
                );
            }
            None => {
                let _ = writeln!(
                    out,
                    "  void cmd_{name}({}) const {{ {call}; }}",
                    params_decl(&c.params)
                );
            }
        }
    }

    // Events: a stored std::function plus a static trampoline.
    let mut event_members = Vec::new();
    for e in &schema.events {
        let name = snake_case(&e.name.0);
        let handler = format!("{name}_handler");
        let _ = writeln!(out);
        let _ = writeln!(out, "  // event `{}`", e.name.0);
        let _ = writeln!(out, "  using {handler} = {};", event_fn_type(e));
        let _ = writeln!(
            out,
            "  void on_{name}({handler} cb) {{ on_{name}_ = std::move(cb); {prefix}_on_{name}(handle_, &{class}::trampoline_{name}, this); }}",
        );
        event_members.push((name, handler, e.clone()));
    }

    let _ = writeln!(out);
    let _ = writeln!(out, "private:");
    if !event_members.is_empty() {
        for (name, handler, _e) in &event_members {
            let _ = writeln!(out, "  {handler} on_{name}_;");
        }
        let _ = writeln!(out);
        for (name, _handler, e) in &event_members {
            let extra = event_trampoline_args(&e.params);
            let sep = if extra.is_empty() { "" } else { ", " };
            let call_args = c_callback_params(&e.params)
                .into_iter()
                .map(|(_, n)| n)
                .collect::<Vec<_>>()
                .join(", ");
            let _ = writeln!(
                out,
                "  static void trampoline_{name}(void *userdata{sep}{extra}) {{"
            );
            let _ = writeln!(out, "    auto *self = static_cast<{class} *>(userdata);");
            let _ = writeln!(
                out,
                "    if (self && self->on_{name}_) self->on_{name}_({call_args});"
            );
            let _ = writeln!(out, "  }}");
        }
    }

    let _ = writeln!(out, "  Handle *handle_;");
    let _ = writeln!(out, "}};");
    let _ = writeln!(out);
    let _ = writeln!(out, "}} // namespace floem_gen");
    let _ = writeln!(out);
    let _ = writeln!(out, "#endif // {guard}");

    vec![super::GeneratedFile::new(format!("{prefix}_glue.hpp"), out)]
}

/// `(a, b)` → `, a, b` for appending args to a call.
fn prefix_args(s: &str) -> String {
    if s.is_empty() {
        String::new()
    } else {
        format!(", {s}")
    }
}

fn access_str(a: Access) -> &'static str {
    match a {
        Access::Read => "read",
        Access::Write => "write",
        Access::ReadWrite => "read/write",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::fixtures;

    #[test]
    fn facade_wraps_properties_commands_and_events() {
        let s = fixtures::demo_video_player();
        let h = &generate(&s)[0].contents;
        assert!(h.contains("#include \"floem_video_player_abi.h\""));
        assert!(h.contains("class VideoPlayer {"));
        assert!(h.contains("void set_src(const std::string& value) { floem_video_player_set_src(handle_, value.c_str()); }"));
        assert!(h.contains("std::string get_src() const {"));
        assert!(h.contains(
            "void cmd_seek(uint64_t ms) const { floem_video_player_cmd_seek(handle_, ms); }"
        ));
        assert!(h.contains(
            "uint64_t cmd_position() const { return floem_video_player_cmd_position(handle_); }"
        ));
        assert!(h.contains("using error_handler = std::function<void(const char *)>;"));
        assert!(h.contains("static void trampoline_error(void *userdata, const char * message) {"));
    }

    #[test]
    fn no_events_means_no_private_section_members() {
        let mut s = fixtures::demo_video_player();
        s.events.clear();
        let h = &generate(&s)[0].contents;
        assert!(!h.contains("trampoline_"));
    }
}
